#!/usr/bin/env python3
"""Generate immutable native palettes from pinned Qwen Code0.24.5 theme data.
Development tool only: make and application runtime use checked-in assembly.
"""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'docs/ui-reference-themes.json').read_text())
by_name={t['name']:t for t in data}
order=['Qwen Dark','Dracula','GitHub','GitHub Light']+[t['name'] for t in data if t['name'] not in {'Qwen Dark','Dracula','GitHub','GitHub Light'}]
ids={name:i for i,name in enumerate(order)}
ANSI={'black':30,'red':31,'green':32,'yellow':33,'blue':34,'magenta':35,'cyan':36,'white':37,'gray':90,'bluebright':94}
def sgr(c='',style=None):
 p=[] if style is None else [str(style)]
 if not c:p+=['39']
 elif c.lower() in ANSI:p+=[str(ANSI[c.lower()])]
 else:
  v=c.lstrip('#');v=''.join(x*2 for x in v) if len(v)==3 else v
  p+=['38','2',*[str(int(v[i:i+2],16)) for i in (0,2,4)]]
 return '\x1b['+';'.join(p)+'m'
def emit_bytes(label,text,nul=False):
 b=text.encode();return label+': .byte '+','.join(map(str,b+(b'\0' if nul else b'')))
header='# Generated by scripts/generate-ui-themes.py; pinned Qwen Code0.24.5 data.\n.equ UI_THEME_COUNT,16\n.equ UI_THEME_PALETTE_COUNT,17\n.equ UI_THEME_AUTO,15\n.section .rodata\n'
ui=[header,'.Lu_all_theme_palettes: .quad '+','.join(f'.Lu_all_theme_{i}' for i in range(15))+',.Lu_all_theme_0,.Lu_all_theme_16']
md=[header,'.m_palettes:'];mer=[header,'.r_palettes:']
for i,name in enumerate(order+['Qwen Dark']):
 t=by_name[name];sem=t['semantic'];syn=t['syntax'];colors=t['colors'];code=syn.get('hljs') or sem['text']['primary']
 roles=['\x1b[1m',sgr(sem['text']['secondary']),sgr(sem['text']['code']),sgr(sem['text']['link'],4),sgr(syn.get('hljs-keyword') or code),sgr(syn.get('hljs-string') or code),sgr(syn.get('hljs-number') or code),sgr(sem['text']['primary']),sgr(sem['text']['accent']),sgr(code),sgr(colors.get('Gray','')),sgr(syn.get('hljs-comment') or code),sgr(syn.get('hljs-literal') or code)]
 for j in range(13):md.append(f' .quad .m_palette_{i}_{j}-.m_palettes,.m_palette_{i}_{j}_len')
 for j in range(3):mer.append(f' .quad .r_palette_{i}_{j}-.r_palettes,.r_palette_{i}_{j}_len')
 if i<15:
  fields=[sem['text']['primary'],sem['text']['secondary'],sem['text']['accent'],sem['status']['success'],sem['status']['error'],sem['status']['warning'],sem['border']['focused']]
  ui.append(f'.Lu_all_theme_{i}: .quad '+','.join(f'.Lu_all_theme_{i}_{j}' for j in range(7)))
  for j,c in enumerate(fields):ui.append(emit_bytes(f'.Lu_all_theme_{i}_{j}',sgr(c),True))
  ui.append(emit_bytes(f'.Lu_theme_name_{i}',name,True))
  ui.append(emit_bytes(f'.Lu_theme_type_{i}',t['type'].capitalize(),True))
 # Store rows for emission after all pointer rows so table strides are contiguous.
 t['_md_roles']=roles
for i,name in enumerate(order+['Qwen Dark']):
 t=by_name[name]
 for j,seq in enumerate(t['_md_roles']):
  md+=[emit_bytes(f'.m_palette_{i}_{j}',seq),f'.equ .m_palette_{i}_{j}_len,.-.m_palette_{i}_{j}']
 sem=t['semantic']
 for j,seq in enumerate([sgr(sem['text']['accent'],1),sgr(sem['text']['primary']),sgr(sem['text']['secondary'])]):
  mer+=[emit_bytes(f'.r_palette_{i}_{j}',seq),f'.equ .r_palette_{i}_{j}_len,.-.r_palette_{i}_{j}']
ui+=[emit_bytes('.Lu_theme_name_15','auto',True),emit_bytes('.Lu_theme_type_15','Auto',True),'.Lu_all_theme_names: .quad '+','.join(f'.Lu_theme_name_{i}' for i in range(16)),'.Lu_all_theme_catalog:']
for n,t in enumerate([{'name':'auto','type':'auto'}]+data):
 name=t['name'];i=15 if name=='auto' else ids[name]
 ui.append(f' .quad .Lu_theme_label_{n},.Lu_theme_type_{i},{i}')
for n,t in enumerate([{'name':'Auto','type':'auto'}]+data):ui.append(emit_bytes(f'.Lu_theme_label_{n}',t['name']+' '+t['type'].capitalize(),True))
ui+=['.Lu_all_theme_16: .quad '+','.join('.Lu_all_theme_16_'+str(j) for j in range(7))]
for j in range(7):ui.append(emit_bytes('.Lu_all_theme_16_'+str(j),sgr(''),True))
# NoColor is an environment override, never a selectable/persisted theme.
for j in reversed(range(13)):md.insert(1+1+16*13,f' .quad .m_palette_16_{j}-.m_palettes,.m_palette_16_{j}_len')
for j in range(13):
 seq='\x1b[1m' if j==0 else sgr('',4) if j==3 else sgr('')
 md+=[emit_bytes(f'.m_palette_16_{j}',seq),f'.equ .m_palette_16_{j}_len,.-.m_palette_16_{j}']
for j in reversed(range(3)):mer.insert(1+1+16*3,f' .quad .r_palette_16_{j}-.r_palettes,.r_palette_16_{j}_len')
for j in range(3):
 seq=sgr('',1) if j==0 else sgr('')
 mer+=[emit_bytes(f'.r_palette_16_{j}',seq),f'.equ .r_palette_16_{j}_len,.-.r_palette_16_{j}']
# tinygradient RGB interpolation: split the N-1 intervals across source stops.
# The36/37cellQwen rows match pinned reference RGB cells exactly.
ui+=['.Lu_theme_gradient_themes: .quad '+','.join('.Lu_theme_gradient_'+str(i) for i in range(15))]
gradient_owners={}
for i,name in enumerate(order):
 nodes=[]
 for c in by_name[name]['semantic']['ui']['gradient']:
  v=c.lstrip('#');v=''.join(x*2 for x in v) if len(v)==3 else v
  nodes.append(tuple(int(v[k:k+2],16) for k in (0,2,4)))
 key=tuple(nodes)
 if key in gradient_owners:
  ui.append(f'.set .Lu_theme_gradient_{i},.Lu_theme_gradient_{gradient_owners[key]}')
  continue
 gradient_owners[key]=i
 ui.append('.Lu_theme_gradient_'+str(i)+': .quad '+','.join(f'.Lu_theme_gradient_{i}_{n}' for n in (36,37)))
 for n in (36,37):
  labels=[]
  stops=[(n-1)*k//(len(nodes)-1) for k in range(len(nodes))]
  for x in range(n):
   k=next((k for k in range(len(stops)-1) if x<=stops[k+1]),len(stops)-2)
   span=stops[k+1]-stops[k];pos=x-stops[k]
   rgb=tuple((nodes[k][z]*(span-pos)+nodes[k+1][z]*pos+span//2)//span for z in range(3))
   label=f'.Lu_gradient_rgb_{i}_{n}_{x}';labels.append(label)
   ui.append(emit_bytes(label,'\x1b[38;2;'+';'.join(map(str,rgb))+'m',True))
  ui.append(f'.Lu_theme_gradient_{i}_{n}: .quad '+','.join(labels))
for name,lines in [('ui_themes.inc',ui),('ui_formatter_palettes.inc',md),('ui_mermaid_palettes.inc',mer)]:
 (ROOT/'src'/name).write_text('\n'.join(lines)+'\n')
print(json.dumps(ids,indent=2));print('Auto=15')
